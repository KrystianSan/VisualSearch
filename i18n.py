def get_text(language: str, key: str, fallback_language: str = "English") -> str:
    """Return translated string; falls back to English if key or language missing."""
    lang_dict = TRANSLATIONS.get(language, TRANSLATIONS[fallback_language])
    return lang_dict.get(key, TRANSLATIONS[fallback_language].get(key, key))
